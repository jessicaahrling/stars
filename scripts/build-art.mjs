// Converts the illustrations in art/<ID>.svg into src/data/art-data.js.
//
//   node scripts/build-art.mjs
//
// Curves are flattened into polylines in the illustration's own frame (see
// src/sky/art-frame.js), quantized to 1/ART_QUANT frame units and delta-encoded.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { readArt } from './lib/svg-art.mjs';
import { CONSTELLATION_NAMES_SV } from '../src/data/names-sv.js';

const ART_QUANT = 4; // 1/4 frame unit = 0.025 degrees
const TOLERANCE = 0.3; // frame units a flattened curve may deviate

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const artDir = path.join(root, 'art');
const outFile = path.join(root, 'src/data/art-data.js');

/** [fine, x0, y0, dx1, dy1, ...] with integer coordinates. */
function encode({ fine, pts }) {
  const out = [fine ? 1 : 0];
  let px = 0;
  let py = 0;
  for (let i = 0; i < pts.length; i += 2) {
    const x = Math.round(pts[i] * ART_QUANT);
    const y = Math.round(pts[i + 1] * ART_QUANT);
    if (i > 0 && x === px && y === py) continue;
    out.push(x - px, y - py);
    px = x;
    py = y;
  }
  return out;
}

const files = (await readdir(artDir)).filter((f) => f.endsWith('.svg')).sort();
const art = {};
let points = 0;
for (const file of files) {
  const id = file.slice(0, -4);
  if (!CONSTELLATION_NAMES_SV[id]) throw new Error(`art/${file}: "${id}" is not an IAU constellation abbreviation`);
  let polylines;
  try {
    polylines = readArt(await readFile(path.join(artDir, file), 'utf8'), TOLERANCE);
  } catch (err) {
    throw new Error(`art/${file}: ${err.message}`);
  }
  art[id] = polylines.map(encode).filter((e) => e.length >= 5);
  points += art[id].reduce((s, e) => s + (e.length - 1) / 2, 0);
}

const missing = Object.keys(CONSTELLATION_NAMES_SV).filter((id) => !art[id]);
const out = `// GENERATED by scripts/build-art.mjs from art/*.svg - do not edit.

/** Frame units are multiplied by this before rounding. */
export const ART_QUANT = ${ART_QUANT};

/**
 * Constellation illustrations as polylines in each constellation's art frame
 * (src/sky/art-frame.js): [fine (0/1), x0, y0, dx1, dy1, ...], integers in
 * 1/ART_QUANT frame units, each point relative to the previous one.
 */
export const ART = {
${Object.entries(art).map(([id, lines]) => `  ${id}: ${JSON.stringify(lines)},`).join('\n')}
};
`;
await writeFile(outFile, out);
console.log(`  wrote ${path.relative(root, outFile)} (${(out.length / 1024).toFixed(0)} kB, ${Object.keys(art).length}/88 constellations, ${points} points)`);
if (missing.length) console.log(`  no illustration yet: ${missing.join(' ')}`);
